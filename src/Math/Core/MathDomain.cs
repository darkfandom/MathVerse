namespace MathVerse.Math.Core;

/// <summary>
/// Defines the numeric domains over which mathematical operations may be performed.
/// </summary>
public enum MathDomain
{
    /// <summary>Real numbers (ℝ).</summary>
    Real,

    /// <summary>Complex numbers (ℂ).</summary>
    Complex,

    /// <summary>Integers (ℤ).</summary>
    Integer,

    /// <summary>Rational numbers (ℚ).</summary>
    Rational,

    /// <summary>Natural numbers (ℕ).</summary>
    Natural
}
