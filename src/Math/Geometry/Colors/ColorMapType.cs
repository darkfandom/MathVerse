namespace MathVerse.Math.Geometry.Colors;

/// <summary>Defines the available scientific and utility colormaps.</summary>
public enum ColorMapType
{
    /// <summary>Viridis perceptually uniform colormap.</summary>
    Viridis,

    /// <summary>Inferno perceptually uniform colormap.</summary>
    Inferno,

    /// <summary>Plasma perceptually uniform colormap.</summary>
    Plasma,

    /// <summary>Magma perceptually uniform colormap.</summary>
    Magma,

    /// <summary>Jet rainbow colormap.</summary>
    Jet,

    /// <summary>Linear grayscale colormap.</summary>
    Grayscale,

    /// <summary>CoolWarm diverging colormap (blue to red).</summary>
    CoolWarm
}
